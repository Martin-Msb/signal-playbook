// Writes apps/site/src/guides/index.ts from the guide files on disk, in curriculum order.
// A guide file is src/guides/<track>/<concept key>.ts. Runs before test, build and dev.
import { readdirSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { concepts } from "../apps/site/src/data/curriculum.ts";

const dir = fileURLToPath(new URL("../apps/site/src/guides/", import.meta.url));
const order = new Map(concepts.map((c, i) => [`${c.track}/${c.key}`, i]));
const found = [];
for (const track of ["data", "ai", "ml"]) {
  if (!existsSync(dir + track)) continue;
  for (const f of readdirSync(dir + track)) if (f.endsWith(".ts")) found.push(`${track}/${f.slice(0, -3)}`);
}
const unknown = found.filter((f) => !order.has(f));
if (unknown.length) {
  console.error(`Guide files that match no concept in the curriculum: ${unknown.join(", ")}`);
  process.exit(1);
}
found.sort((a, b) => order.get(a) - order.get(b));
const out = `// Generated by scripts/gen-guides.mjs from the files in this folder. Do not edit.
import type { Guide } from "@signal-path/engine";
${found.map((f, i) => `import g${i} from "./${f}.ts";`).join("\n")}

/** Every guide that has a page, in curriculum order. */
export const guides: Guide[] = [${found.map((_, i) => `g${i}`).join(", ")}];
`;
writeFileSync(dir + "index.ts", out);
console.log(`guides: ${found.length} of ${concepts.length} concepts`);
